"""TPC-H's subquery queries through the lazy frontend, against DuckDB.

Each query is written with ``exists``, ``isin`` over a table, ``as_scalar``,
``outer`` and ``shared`` — the shapes the decorrelator plans — and its answer
is compared with DuckDB's for the official SQL over the same Parquet files,
generated by DuckDB's ``dbgen`` at scale 0.01. Decimals are written as
doubles, so the two engines read the same values and answers compare to a
relative tolerance. Rows are compared as sorted lists: ``ORDER BY`` and
``LIMIT`` are left to the SQL side's full answer, which at this scale holds
fewer than a hundred rows for every query here. Dates are compared through
the filters that read them, not in an answer: a `date32` cannot yet come
back through `to_pylist`.
"""

import datetime

import pytest

import marrow as ma
from marrow import col, count_star, exists, outer

duckdb = pytest.importorskip("duckdb")

TABLES = (
    "part",
    "supplier",
    "partsupp",
    "customer",
    "orders",
    "lineitem",
    "nation",
    "region",
)


def date(y, m, d):
    """A `date32` literal, built from its day number: the binding cannot
    yet take a `datetime.date` or parse a string into one."""
    days = (datetime.date(y, m, d) - datetime.date(1970, 1, 1)).days
    return ma.lit(days, ma.int32()).cast(ma.date32())


class Tpch:
    """The eight tables, as lazy scans and as DuckDB views of one file each."""

    def __init__(self, root):
        self.db = duckdb.connect()
        self.db.execute("INSTALL tpch; LOAD tpch; CALL dbgen(sf=0.01)")
        for name in TABLES:
            cols = self.db.execute(f"DESCRIBE {name}").fetchall()
            select = ", ".join(
                f"CAST({c} AS DOUBLE) AS {c}" if t.startswith("DECIMAL") else c
                for c, t, *_ in cols
            )
            path = root / f"{name}.parquet"
            self.db.execute(
                f"COPY (SELECT {select} FROM {name}) TO '{path}' (FORMAT parquet)"
            )
            self.db.execute(f"DROP TABLE {name}")
            self.db.execute(
                f"CREATE VIEW {name} AS SELECT * FROM read_parquet('{path}')"
            )
            setattr(self, name, ma.read_parquet(str(path)))

    def sql(self, query):
        return self.db.execute(query).fetchall()


@pytest.fixture(scope="module")
def tpch(tmp_path_factory):
    return Tpch(tmp_path_factory.mktemp("tpch"))


def _norm(v):
    if isinstance(v, float):
        return float(f"{v:.6g}")
    return v


def assert_same(lazy, expected, columns):
    rows = lazy.select(*columns).collect().to_pylist()
    got = [tuple(_norm(r[c]) for c in columns) for r in rows]
    want = [tuple(_norm(v) for v in row) for row in expected]
    key = lambda row: tuple((x is None, x) for x in row)
    assert sorted(got, key=key) == sorted(want, key=key)


def test_tpch_q2_correlated_min(tpch):
    def europe():
        return (
            tpch.partsupp.join(
                tpch.supplier, left_on="ps_suppkey", right_on="s_suppkey"
            )
            .join(tpch.nation, left_on="s_nationkey", right_on="n_nationkey")
            .join(
                tpch.region.filter(col("r_name") == "EUROPE"),
                left_on="n_regionkey",
                right_on="r_regionkey",
            )
        )

    cheapest = (
        europe()
        .filter(col("ps_partkey") == outer("p_partkey"))
        .aggregate(m=col("ps_supplycost").min())
    )
    parts = tpch.part.filter((col("p_size") == 15) & col("p_type").like("%BRASS"))
    got = parts.join(europe(), left_on="p_partkey", right_on="ps_partkey").filter(
        col("ps_supplycost") == cheapest.as_scalar()
    )
    want = tpch.sql(
        """
        select s_acctbal, s_name, n_name, p_partkey, p_mfgr
        from part, supplier, partsupp, nation, region
        where p_partkey = ps_partkey and s_suppkey = ps_suppkey
          and p_size = 15 and p_type like '%BRASS'
          and s_nationkey = n_nationkey and n_regionkey = r_regionkey
          and r_name = 'EUROPE'
          and ps_supplycost = (
            select min(ps_supplycost)
            from partsupp, supplier, nation, region
            where p_partkey = ps_partkey and s_suppkey = ps_suppkey
              and s_nationkey = n_nationkey and n_regionkey = r_regionkey
              and r_name = 'EUROPE')
        """
    )
    assert_same(got, want, ["s_acctbal", "s_name", "n_name", "p_partkey", "p_mfgr"])


def test_tpch_q4_exists(tpch):
    late = tpch.lineitem.filter(
        (col("l_orderkey") == outer("o_orderkey"))
        & (col("l_commitdate") < col("l_receiptdate"))
    )
    got = tpch.orders.filter(
        (col("o_orderdate") >= date(1993, 7, 1))
        & (col("o_orderdate") < date(1993, 10, 1))
        & exists(late)
    ).aggregate(by=["o_orderpriority"], order_count=count_star())
    want = tpch.sql(
        """
        select o_orderpriority, count(*) from orders
        where o_orderdate >= date '1993-07-01' and o_orderdate < date '1993-10-01'
          and exists (select * from lineitem
                      where l_orderkey = o_orderkey and l_commitdate < l_receiptdate)
        group by o_orderpriority
        """
    )
    assert_same(got, want, ["o_orderpriority", "order_count"])


def test_tpch_q11_having_scalar(tpch):
    def germany():
        return tpch.partsupp.join(
            tpch.supplier, left_on="ps_suppkey", right_on="s_suppkey"
        ).join(
            tpch.nation.filter(col("n_name") == "GERMANY"),
            left_on="s_nationkey",
            right_on="n_nationkey",
        )

    worth = col("ps_supplycost") * col("ps_availqty")
    threshold = (
        germany().aggregate(v=worth.sum()).with_columns(t=col("v") * 0.0001).select("t")
    )
    got = (
        germany()
        .aggregate(by=["ps_partkey"], value=worth.sum())
        .filter(col("value") > threshold.as_scalar())
    )
    want = tpch.sql(
        """
        select ps_partkey, sum(ps_supplycost * ps_availqty) as value
        from partsupp, supplier, nation
        where ps_suppkey = s_suppkey and s_nationkey = n_nationkey
          and n_name = 'GERMANY'
        group by ps_partkey
        having sum(ps_supplycost * ps_availqty) > (
          select sum(ps_supplycost * ps_availqty) * 0.0001
          from partsupp, supplier, nation
          where ps_suppkey = s_suppkey and s_nationkey = n_nationkey
            and n_name = 'GERMANY')
        """
    )
    assert_same(got, want, ["ps_partkey", "value"])


def test_tpch_q15_shared_view(tpch):
    revenue = (
        tpch.lineitem.filter(
            (col("l_shipdate") >= date(1996, 1, 1))
            & (col("l_shipdate") < date(1996, 4, 1))
        )
        .aggregate(
            by=["l_suppkey"],
            total_revenue=(col("l_extendedprice") * (1 - col("l_discount"))).sum(),
        )
        .shared()
    )
    top = revenue.aggregate(m=col("total_revenue").max())
    got = tpch.supplier.join(revenue, left_on="s_suppkey", right_on="l_suppkey").filter(
        col("total_revenue") == top.as_scalar()
    )
    want = tpch.sql(
        """
        with revenue as (
          select l_suppkey as supplier_no,
                 sum(l_extendedprice * (1 - l_discount)) as total_revenue
          from lineitem
          where l_shipdate >= date '1996-01-01' and l_shipdate < date '1996-04-01'
          group by l_suppkey)
        select s_suppkey, s_name, total_revenue from supplier, revenue
        where s_suppkey = supplier_no
          and total_revenue = (select max(total_revenue) from revenue)
        """
    )
    assert_same(got, want, ["s_suppkey", "s_name", "total_revenue"])
    assert "Shared#" in got.optimize().explain()


def test_tpch_q16_not_in(tpch):
    complaints = tpch.supplier.filter(
        col("s_comment").like("%Customer%Complaints%")
    ).select("s_suppkey")
    got = (
        tpch.partsupp.join(tpch.part, left_on="ps_partkey", right_on="p_partkey")
        .filter(
            (col("p_brand") != "Brand#45")
            & ~col("p_type").like("MEDIUM POLISHED%")
            & col("p_size").isin([49, 14, 23, 45, 19, 3, 36, 9])
            & ~col("ps_suppkey").isin(complaints)
        )
        .aggregate(
            by=["p_brand", "p_type", "p_size"],
            supplier_cnt=col("ps_suppkey").count_distinct(),
        )
    )
    want = tpch.sql(
        """
        select p_brand, p_type, p_size, count(distinct ps_suppkey)
        from partsupp, part
        where p_partkey = ps_partkey and p_brand <> 'Brand#45'
          and p_type not like 'MEDIUM POLISHED%'
          and p_size in (49, 14, 23, 45, 19, 3, 36, 9)
          and ps_suppkey not in (select s_suppkey from supplier
                                 where s_comment like '%Customer%Complaints%')
        group by p_brand, p_type, p_size
        """
    )
    assert_same(got, want, ["p_brand", "p_type", "p_size", "supplier_cnt"])


def test_tpch_q17_correlated_avg(tpch):
    small = (
        tpch.lineitem.filter(col("l_partkey") == outer("p_partkey"))
        .aggregate(a=col("l_quantity").mean())
        .with_columns(q=col("a") * 0.2)
        .select("q")
    )
    got = (
        tpch.lineitem.join(
            tpch.part.filter(
                (col("p_brand") == "Brand#23") & (col("p_container") == "MED BOX")
            ),
            left_on="l_partkey",
            right_on="p_partkey",
        )
        .filter(col("l_quantity") < small.as_scalar())
        .aggregate(s=col("l_extendedprice").sum())
    )
    want = tpch.sql(
        """
        select sum(l_extendedprice) from lineitem, part
        where p_partkey = l_partkey and p_brand = 'Brand#23'
          and p_container = 'MED BOX'
          and l_quantity < (select 0.2 * avg(l_quantity) from lineitem
                            where l_partkey = p_partkey)
        """
    )
    assert_same(got, want, ["s"])


def test_tpch_q18_in_having(tpch):
    big = (
        tpch.lineitem.aggregate(by=["l_orderkey"], q=col("l_quantity").sum())
        .filter(col("q") > 300)
        .select("l_orderkey")
    )
    got = (
        tpch.customer.join(tpch.orders, left_on="c_custkey", right_on="o_custkey")
        .join(tpch.lineitem, left_on="o_orderkey", right_on="l_orderkey")
        .filter(col("o_orderkey").isin(big))
        .aggregate(
            by=["c_name", "c_custkey", "o_orderkey", "o_orderdate", "o_totalprice"],
            qty=col("l_quantity").sum(),
        )
    )
    want = tpch.sql(
        """
        select c_name, c_custkey, o_orderkey, o_totalprice, sum(l_quantity)
        from customer, orders, lineitem
        where o_orderkey in (select l_orderkey from lineitem group by l_orderkey
                             having sum(l_quantity) > 300)
          and c_custkey = o_custkey and o_orderkey = l_orderkey
        group by c_name, c_custkey, o_orderkey, o_orderdate, o_totalprice
        """
    )
    assert_same(
        got,
        want,
        ["c_name", "c_custkey", "o_orderkey", "o_totalprice", "qty"],
    )


def test_tpch_q20_nested(tpch):
    forest = tpch.part.filter(col("p_name").like("forest%")).select("p_partkey")
    shipped = (
        tpch.lineitem.filter(
            (col("l_partkey") == outer("ps_partkey"))
            & (col("l_suppkey") == outer("ps_suppkey"))
            & (col("l_shipdate") >= date(1994, 1, 1))
            & (col("l_shipdate") < date(1995, 1, 1))
        )
        .aggregate(q=col("l_quantity").sum())
        .with_columns(h=col("q") * 0.5)
        .select("h")
    )
    suppliers = tpch.partsupp.filter(
        col("ps_partkey").isin(forest) & (col("ps_availqty") > shipped.as_scalar())
    ).select("ps_suppkey")
    got = (
        tpch.supplier.join(
            tpch.nation.filter(col("n_name") == "CANADA"),
            left_on="s_nationkey",
            right_on="n_nationkey",
        )
        .filter(col("s_suppkey").isin(suppliers))
        .select("s_name", "s_address")
    )
    want = tpch.sql(
        """
        select s_name, s_address from supplier, nation
        where s_suppkey in (
            select ps_suppkey from partsupp
            where ps_partkey in (select p_partkey from part
                                 where p_name like 'forest%')
              and ps_availqty > (
                select 0.5 * sum(l_quantity) from lineitem
                where l_partkey = ps_partkey and l_suppkey = ps_suppkey
                  and l_shipdate >= date '1994-01-01'
                  and l_shipdate < date '1995-01-01'))
          and s_nationkey = n_nationkey and n_name = 'CANADA'
        """
    )
    assert_same(got, want, ["s_name", "s_address"])


def test_tpch_q21_residual(tpch):
    other = tpch.lineitem.filter(
        (col("l_orderkey") == outer("l_orderkey"))
        & (col("l_suppkey") != outer("l_suppkey"))
    )
    other_late = other.filter(col("l_receiptdate") > col("l_commitdate"))
    got = (
        tpch.supplier.join(tpch.lineitem, left_on="s_suppkey", right_on="l_suppkey")
        .join(
            tpch.orders.filter(col("o_orderstatus") == "F"),
            left_on="l_orderkey",
            right_on="o_orderkey",
        )
        .join(
            tpch.nation.filter(col("n_name") == "SAUDI ARABIA"),
            left_on="s_nationkey",
            right_on="n_nationkey",
        )
        .filter(
            (col("l_receiptdate") > col("l_commitdate"))
            & exists(other)
            & ~exists(other_late)
        )
        .aggregate(by=["s_name"], numwait=count_star())
    )
    want = tpch.sql(
        """
        select s_name, count(*) from supplier, lineitem l1, orders, nation
        where s_suppkey = l1.l_suppkey and o_orderkey = l1.l_orderkey
          and o_orderstatus = 'F' and l1.l_receiptdate > l1.l_commitdate
          and exists (select * from lineitem l2
                      where l2.l_orderkey = l1.l_orderkey
                        and l2.l_suppkey <> l1.l_suppkey)
          and not exists (select * from lineitem l3
                          where l3.l_orderkey = l1.l_orderkey
                            and l3.l_suppkey <> l1.l_suppkey
                            and l3.l_receiptdate > l3.l_commitdate)
          and s_nationkey = n_nationkey and n_name = 'SAUDI ARABIA'
        group by s_name
        """
    )
    assert_same(got, want, ["s_name", "numwait"])


def test_tpch_q22_not_exists_and_scalar(tpch):
    codes = ["13", "31", "23", "29", "30", "18", "17"]
    customers = tpch.customer.with_columns(cntrycode=col("c_phone").substr(1, 2))
    average = customers.filter(
        (col("c_acctbal") > 0.0) & col("cntrycode").isin(codes)
    ).aggregate(a=col("c_acctbal").mean())
    ordered = tpch.orders.filter(col("o_custkey") == outer("c_custkey"))
    got = customers.filter(
        col("cntrycode").isin(codes)
        & (col("c_acctbal") > average.as_scalar())
        & ~exists(ordered)
    ).aggregate(
        by=["cntrycode"], numcust=count_star(), totacctbal=col("c_acctbal").sum()
    )
    want = tpch.sql(
        """
        select cntrycode, count(*), sum(c_acctbal) from (
          select substring(c_phone from 1 for 2) as cntrycode, c_acctbal
          from customer
          where substring(c_phone from 1 for 2)
                  in ('13', '31', '23', '29', '30', '18', '17')
            and c_acctbal > (
              select avg(c_acctbal) from customer
              where c_acctbal > 0.00
                and substring(c_phone from 1 for 2)
                      in ('13', '31', '23', '29', '30', '18', '17'))
            and not exists (select * from orders where o_custkey = c_custkey))
        group by cntrycode
        """
    )
    assert_same(got, want, ["cntrycode", "numcust", "totacctbal"])
