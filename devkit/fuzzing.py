@dataclass(frozen=True)
class Entry:
    """One committed input and what replaying it must do."""

    path: Path
    verdict: str
    bug: str = ""
    match: str = ""
    note: str = ""
    sanitizer: str = ""

    @property
    def name(self):
        return self.path.name

    def skip_reason(self, asan):
        """Why a replay without a sanitizer cannot judge this entry, or None.

        A read a few bytes past an allocation corrupts nothing a plain build
        notices, so such a reproducer is accepted there; only an ASAN replay
        tells it from a fixed bug.
        """
        if self.sanitizer == "address" and not asan:
            return (
                f"{self.name} crashes only under AddressSanitizer; replay with --asan"
            )
        return None


class Expectations:
    """`fuzz/corpus/<target>/expected.toml`: every input's verdict.

        ["b1-slice-body.arrows"]
        verdict = "crash"
        bug = "B1"
        match = "out of bounds"

    `match` is a substring the crash output has to contain, so a reproducer
    that starts failing somewhere else is reported rather than counted.
    `sanitizer = "address"` marks a reproducer only an ASAN replay catches.
    """

    FILE = "expected.toml"

    def __init__(self, directory, entries):
        self.directory = Path(directory)
        self.entries = entries

    @classmethod
    def load(cls, directory):
        directory = Path(directory)
        manifest = directory / cls.FILE
        table = tomllib.loads(manifest.read_text()) if manifest.exists() else {}
        entries = []
        for name, spec in table.items():
            verdict = spec.get("verdict", "")
            if verdict not in VERDICTS:
                raise ValueError(
                    f"{manifest}: {name!r} has verdict {verdict!r}; "
                    f"expected one of {', '.join(VERDICTS)}"
                )
            entries.append(
                Entry(
                    directory / name,
                    verdict,
                    spec.get("bug", ""),
                    spec.get("match", ""),
                    spec.get("note", ""),
                    spec.get("sanitizer", ""),
                )
            )
        return cls(directory, entries)

    def problems(self):
        """Files with no verdict, and verdicts naming no file."""
        listed = {entry.name for entry in self.entries}
        present = (
            {p.name for p in self.directory.iterdir() if p.name != self.FILE}
            if self.directory.exists()
            else set()
        )
        found = [f"{name}: no verdict in {self.FILE}" for name in present - listed]
        found += [
            f"{name}: listed in {self.FILE} but missing" for name in listed - present
        ]
        return sorted(found)


@dataclass(frozen=True)
class Outcome:
    """What one replayed input did."""

    verdict: str
    output: str

    @classmethod
    def of(cls, result):
        if result.ok and "accept" in result.stdout.split():
            return cls("accept", result.output)
        if result.ok and result.stdout.startswith("reject:"):
            return cls("reject", result.output)
        return cls("crash", result.output)


def judge(entry, outcome):
    """None if *outcome* is what *entry* expects, else why not."""
    if outcome.verdict == entry.verdict:
        if (
            entry.verdict == "crash"
            and entry.match
            and entry.match not in outcome.output
        ):
            return (
                f"{entry.name}: still crashes, but no longer with {entry.match!r} -- "
                f"now: {signature(outcome.output)}\n{outcome.output[-4000:]}"
            )
        return None
    if entry.verdict == "crash":
        return (
            f"{entry.name}: expected a crash ({entry.bug or 'unnamed bug'}) and got "
            f"{outcome.verdict} -- if the bug is fixed, change its verdict in "
            f"{Expectations.FILE}\n{outcome.output[-2000:]}"
        )
    return (
        f"{entry.name}: expected {entry.verdict}, got {outcome.verdict}"
        f" ({signature(outcome.output) if outcome.verdict == 'crash' else ''})\n"
        f"{outcome.output[-4000:]}"
    )


class Replay:
    """Every target behind one `main()`, and each committed input through it.

    With `asan` the driver is built against the AddressSanitizer runtime (the
    `asan` pixi environment), which is the only replay that can judge an entry
    marked `sanitizer = "address"`.
    """

    def __init__(self, repo, toolchain, asan=False):
        self._repo = repo
        self._targets = Targets(repo)
        self._mojo = toolchain
        self.asan = asan

    @property
    def binary(self):
        flavor = "replay-asan" if self.asan else "replay"
        return self._repo.fuzz_work_dir / "replay" / f"{flavor}-{PLATFORM}"

    def build(self):
        """Compile the replay driver; returns the result, `ok` or not.

        This is also the compile check for `fuzz/`: `precompile` stops at
        `marrow/`, so a harness nothing builds would rot unnoticed.
        """
        source = write_if_changed(
            self._repo.fuzz_work_dir / "replay" / "replay.mojo",
            replay_source(self._targets.names()),
        )
        return self._mojo.build(
            source,
            self.binary,
            BuildOptions.for_fuzz_replay(asan=self.asan),
            "building fuzz replay",
        )

    def entries(self, names=None):
        """`(target, entry)` for every committed input."""
        for name in names or self._targets.names():
            for entry in Expectations.load(self._targets.corpus(name)).entries:
                yield name, entry

    def run(self, target, entry):
        result = self._mojo.execute(
            self.binary,
            [target, entry.path],
            f"replaying {target}/{entry.name}",
            env=Fuzzer.environment(),
        )
        return Outcome.of(result)


