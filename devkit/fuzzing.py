@dataclass(frozen=True)
class RunOptions:
    """One fuzzing session's libFuzzer flags."""

    seconds: int = 120
    jobs: int = 0
    max_len: int = 1 << 16
    timeout: int = 10
    rss_limit_mb: int = 2048

    def flags(self, artifacts):
        flags = [
            f"-max_total_time={self.seconds}",
            f"-max_len={self.max_len}",
            f"-timeout={self.timeout}",
            f"-rss_limit_mb={self.rss_limit_mb}",
            f"-artifact_prefix={artifacts}/",
            "-print_final_stats=1",
        ]
        if self.jobs:
            # Fork mode survives a crash and keeps going, which is what a
            # session over a reader with known bugs needs to find the rest.
            flags += [f"-fork={self.jobs}", "-ignore_crashes=1", "-ignore_ooms=1"]
            flags += ["-ignore_timeouts=1"]
        return flags


class Fuzzer:
    """Builds a target into a libFuzzer binary and runs it."""

    def __init__(self, repo, toolchain, clang, runner):
        self._repo = repo
        self._targets = Targets(repo)
        self._mojo = toolchain
        self._clang = clang
        self._runner = runner

    def binary(self, name):
        return self._targets.work(name) / f"fuzz_{name}-{PLATFORM}"

    def build(self, name):
        """Emit *name*'s bitcode and link it; returns the binary."""
        work = self._targets.work(name)
        entry = write_if_changed(work / "entry.mojo", entry_source(name))
        bitcode = work / f"{name}-{PLATFORM}.bc"
        result = self._mojo.emit_bitcode(
            entry, bitcode, BuildOptions.for_fuzzing(), f"emitting {name} bitcode"
        )
        if self._mojo.reports_errors(result):
            raise RuntimeError(result.failure(f"{name}: bitcode emission failed"))
        result = self._clang.link_fuzzer(
            bitcode,
            self.binary(name),
            Clang.mojo_lib_dir(),
            f"linking fuzz_{name}",
        )
        if not result.ok:
            raise RuntimeError(result.failure(f"{name}: clang failed"))
        return self.binary(name)

    def seed(self, name):
        """Write the seed corpus; returns the directory and how many seeds."""
        directory = self._targets.work(name) / "seeds"
        directory.mkdir(parents=True, exist_ok=True)
        count = 0
        for label, data in SEEDS.get(name, lambda: [])():
            (directory / label).write_bytes(data)
            count += 1
        return directory, count

    def run(self, name, options, extra=()):
        """A session over the working corpus, seeded from `seed`.

        New inputs go to the working corpus, the first directory; the seeds
        and the committed corpus's `accept` entries are read only.
        """
        work = self._targets.work(name)
        corpus = work / "corpus"
        artifacts = work / "artifacts"
        for directory in (corpus, artifacts):
            directory.mkdir(parents=True, exist_ok=True)
        seeds, _ = self.seed(name)
        dirs = [corpus, seeds]
        anchors = self.anchor_dir(name)
        if anchors is not None:
            dirs.append(anchors)
        return self._runner.run(
            [self.binary(name), *options.flags(artifacts), *extra, *dirs],
            f"fuzzing {name} for {options.seconds}s",
            env=self.environment(),
        )

    def anchor_dir(self, name):
        """The committed inputs that must be accepted, staged where libFuzzer
        can read them as a corpus -- crash entries would end the session on
        its first input."""
        expected = Expectations.load(self._targets.corpus(name))
        accepted = [e for e in expected.entries if e.verdict == "accept"]
        if not accepted:
            return None
        directory = self._targets.work(name) / "anchors"
        shutil.rmtree(directory, ignore_errors=True)
        directory.mkdir(parents=True)
        for entry in accepted:
            shutil.copyfile(entry.path, directory / entry.path.name)
        return directory

    def execute(self, name, inputs, extra=()):
        """Run the libFuzzer binary over *inputs* once each, no mutation."""
        return self._runner.run(
            [self.binary(name), *extra, *inputs],
            f"running fuzz_{name}",
            env=self.environment(),
        )

    def minimize(self, name, crash, out, runs=10000):
        """The smallest input that still crashes the way *crash* does."""
        return self._runner.run(
            [
                self.binary(name),
                "-minimize_crash=1",
                f"-runs={runs}",
                f"-exact_artifact_path={out}",
                crash,
            ],
            f"minimizing {Path(crash).name}",
            env=self.environment(),
        )

    @staticmethod
    def environment():
        """AddressSanitizer settings for every run.

        `detect_leaks=0`: a harness that raises leaves what it allocated to
        Mojo's destructors, and a leak report would bury the crash that
        mattered.  `abort_on_error=1` makes a report a signal, which is what
        fork mode counts.

        `MARROW_DYLIB_DIR` names where the codec libraries are.  On Linux the
        binary's runpath finds them -- until GCC's ASAN runtime intercepts
        `dlopen`, which makes the loader search the runtime's paths instead.
        """
        env = dict(os.environ)
        env.setdefault("ASAN_OPTIONS", "detect_leaks=0:abort_on_error=1")
        env.setdefault("MARROW_DYLIB_DIR", str(Clang.mojo_lib_dir(env)))
        return env


