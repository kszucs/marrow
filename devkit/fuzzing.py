class BitcodeVersionError(RuntimeError):
    """clang is older than the LLVM that wrote Mojo's bitcode."""


class Clang:
    """The clang that instruments Mojo's bitcode and links libFuzzer.

    It has to read bitcode from Mojo's LLVM, which runs ahead of every
    released toolchain -- Xcode's clang cannot, and says only "Unknown
    attribute kind".  The `fuzz` pixi environment carries a conda-forge clang
    that can; outside it, a Homebrew LLVM is the fallback on macOS.
    """

    HOMEBREW = Path("/opt/homebrew/opt/llvm/bin/clang")

    #: The Mojo runtime a harness's bitcode calls into.
    MOJO_LIBS = (
        "KGENCompilerRTShared",
        "AsyncRTMojoBindings",
        "AsyncRTRuntimeGlobals",
        "MSupportGlobals",
    )

    #: How LLVM reports bitcode from a newer producer.
    UNREADABLE = re.compile(r"Producer: '([^']+)' Reader: '([^']+)'")

    def __init__(self, path, runner):
        self.path = Path(path)
        self._runner = runner

    def __repr__(self):
        return f"Clang({str(self.path)!r})"

    @classmethod
    def locate(cls, runner, env=None):
        """The environment's clang, else Homebrew's on macOS; None if neither."""
        env = os.environ if env is None else env
        prefix = env.get("CONDA_PREFIX")
        candidates = [Path(prefix) / "bin" / "clang"] if prefix else []
        if sys.platform == "darwin":
            candidates.append(cls.HOMEBREW)
        for candidate in candidates:
            if candidate.exists():
                return cls(candidate, runner)
        return None

    @staticmethod
    def mojo_lib_dir(env=None):
        """Where the Mojo runtime libraries are: the pixi environment's lib."""
        env = os.environ if env is None else env
        return Path(env.get("CONDA_PREFIX") or sys.prefix) / "lib"

    def link_flags(self, lib_dir):
        flags = ["-L", str(lib_dir), *(f"-l{lib}" for lib in self.MOJO_LIBS)]
        flags += [f"-Wl,-rpath,{lib_dir}"]
        if sys.platform != "darwin":
            flags += ["-lm"]
        return flags

    def link_fuzzer(self, bitcode, out, lib_dir, label):
        """Instrument *bitcode* and link it against libFuzzer.

        Raises `BitcodeVersionError` when clang cannot read the bitcode at all,
        since every other failure message would bury that one line.
        """
        result = self._runner.run(
            [
                self.path,
                "-O1",
                "-g",
                "-fsanitize=fuzzer,address",
                # Mojo stamps the host triple's OS version; clang's is the
                # one that matters for the link, and saying so is noise.
                "-Wno-override-module",
                bitcode,
                *self.link_flags(lib_dir),
                "-o",
                out,
            ],
            label,
        )
        if not result.ok:
            found = self.UNREADABLE.search(result.output)
            if found:
                raise BitcodeVersionError(
                    f"{self.path} cannot read Mojo's bitcode: it was written by "
                    f"{found.group(1)} and this clang is {found.group(2)}. "
                    "Use the `fuzz` pixi environment, whose clang tracks Mojo's "
                    "LLVM (`pixi run -e fuzz ...`)."
                )
        return result


