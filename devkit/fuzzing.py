def _sample_table(rows=64):
    """One table over the layouts the readers decode: primitives, booleans,
    strings, lists, structs and dictionaries, each with nulls."""
    import pyarrow as pa

    def nulls(values):
        return [None if i % 7 == 3 else v for i, v in enumerate(values)]

    return pa.table(
        {
            "i64": pa.array(nulls(list(range(rows))), pa.int64()),
            "i32": pa.array(nulls([i * 3 - 50 for i in range(rows)]), pa.int32()),
            "f64": pa.array(nulls([i / 4 for i in range(rows)]), pa.float64()),
            "flag": pa.array(nulls([i % 3 == 0 for i in range(rows)]), pa.bool_()),
            "s": pa.array(nulls([f"v{i % 11}" * (i % 4) for i in range(rows)])),
            "l": pa.array(
                nulls([list(range(i % 5)) for i in range(rows)]), pa.list_(pa.int32())
            ),
            "st": pa.array(
                nulls([{"a": i, "b": str(i)} for i in range(rows)]),
                pa.struct([("a", pa.int16()), ("b", pa.string())]),
            ),
            "d": pa.array(
                nulls([f"k{i % 3}" for i in range(rows)])
            ).dictionary_encode(),
        }
    )


def _tables():
    """`(label, table)` -- the whole sample, each column alone, and empty."""
    table = _sample_table()
    yield "all", table
    yield "empty", table.slice(0, 0)
    for name in table.column_names:
        yield name, table.select([name]).slice(0, 9)


def ipc_stream_seeds():
    import pyarrow as pa

    for label, table in _tables():
        sink = pa.BufferOutputStream()
        with pa.ipc.new_stream(sink, table.schema) as writer:
            for batch in table.to_batches(max_chunksize=16) or [table]:
                writer.write(batch)
        yield f"{label}.arrows", sink.getvalue().to_pybytes()


def ipc_file_seeds():
    import pyarrow as pa

    for label, table in _tables():
        sink = pa.BufferOutputStream()
        with pa.ipc.new_file(sink, table.schema) as writer:
            for batch in table.to_batches(max_chunksize=16) or [table]:
                writer.write(batch)
        yield f"{label}.arrow", sink.getvalue().to_pybytes()


def parquet_seeds():
    """Every codec, both data page versions, the non-default encodings, and a
    page index over several small pages."""
    import pyarrow as pa
    import pyarrow.parquet as pq

    table = _sample_table()
    flat = table.select(["i64", "i32", "f64", "flag", "s"])
    variants = [
        (codec, {"compression": codec})
        for codec in ("none", "snappy", "zstd", "gzip", "brotli", "lz4")
    ]
    variants += [
        ("v2", {"data_page_version": "2.0", "compression": "zstd"}),
        ("plain", {"use_dictionary": False}),
        ("index", {"write_page_index": True, "data_page_size": 128}),
        ("stats-off", {"write_statistics": False}),
    ]
    for label, kwargs in variants:
        sink = pa.BufferOutputStream()
        pq.write_table(table, sink, **kwargs)
        yield f"{label}.parquet", sink.getvalue().to_pybytes()
    sink = pa.BufferOutputStream()
    pq.write_table(
        flat,
        sink,
        use_dictionary=False,
        column_encoding={
            "i64": "DELTA_BINARY_PACKED",
            "i32": "DELTA_BINARY_PACKED",
            "f64": "BYTE_STREAM_SPLIT",
            "s": "DELTA_BYTE_ARRAY",
        },
        write_page_index=True,
        data_page_size=64,
    )
    yield "delta.parquet", sink.getvalue().to_pybytes()
    sink = pa.BufferOutputStream()
    pq.write_table(
        flat.select(["s"]),
        sink,
        use_dictionary=False,
        column_encoding={"s": "DELTA_LENGTH_BYTE_ARRAY"},
    )
    yield "delta-length.parquet", sink.getvalue().to_pybytes()


def _payloads():
    yield "empty", b""
    yield "text", b"the quick brown fox jumps over the lazy dog " * 20
    yield "runs", b"a" * 1000 + b"b" * 1000
    yield "mixed", bytes(range(256)) * 4
    yield "ints", b"".join(i.to_bytes(4, "little") for i in range(512))


def snappy_seeds():
    import pyarrow as pa

    for label, data in _payloads():
        yield f"{label}.bin", pa.compress(data, codec="snappy", asbytes=True)


#: `Compression` codes against the pyarrow codec that writes their format;
#: code 0 is the uncompressed copy.  Order and codes match `fuzz/codecs.mojo`.
CODECS = {
    0: None,
    1: "snappy",
    2: "gzip",
    4: "brotli",
    5: "lz4_raw",
    6: "zstd",
    7: "lz4_raw",
}


def codecs_seeds():
    import pyarrow as pa

    for selector, (code, codec) in enumerate(CODECS.items()):
        for label, data in _payloads():
            packed = (
                data if codec is None else pa.compress(data, codec=codec, asbytes=True)
            )
            header = bytes([selector]) + len(data).to_bytes(3, "little")
            yield f"{code}-{label}.bin", header + packed


