#: Where a failed `debug_assert` points: `At: ./marrow/ipc.mojo:2007:30:`.
ASSERT_AT = re.compile(r"At: \.?/?(marrow/[\w/]+\.mojo:\d+)")
#: A symbolized frame in marrow: `in marrow::ipc::_BatchDecoder::read_array(...) ipc.mojo:2018`.
MARROW_FRAME = re.compile(
    r" in (marrow::[\w:]+)[^\n]*?(?: (\w+\.mojo(?::\d+)?))?$", re.M
)
#: The sanitizer's one-line verdict: `SUMMARY: AddressSanitizer: heap-buffer-overflow ...`.
SANITIZER = re.compile(r"SUMMARY: (AddressSanitizer|libFuzzer): ([\w-]+)")
MESSAGE = re.compile(r"(?:Assert Error|ABORT):?\s*([^\n]+)")


def signature(output):
    """What bucket a crash belongs in: the failure, and where in marrow.

    The failure is the sanitizer's kind or the abort message, with numbers
    blanked so two inputs overflowing by different amounts share a bucket.
    The location is the failed assertion's line, else the first stack frame
    inside marrow -- the code the input actually broke.
    """
    what = "unknown"
    found = SANITIZER.search(output)
    message = MESSAGE.search(output)
    if found and found.group(1) == "AddressSanitizer":
        what = f"asan: {found.group(2)}"
    elif message:
        what = re.sub(r"-?\d+", "N", message.group(1).strip())[:120]
    elif found:
        what = f"libfuzzer: {found.group(2)}"
    at = ASSERT_AT.search(output)
    frame = MARROW_FRAME.search(output)
    if at and not (found and found.group(1) == "AddressSanitizer"):
        where = at.group(1)
    elif frame:
        where = " ".join(part for part in frame.groups() if part)
    else:
        where = "no marrow frame"
    return f"{what} @ {where}"


def executions(log):
    """How many inputs a session ran, from libFuzzer's status lines.

    Fork mode reports `exec/s: 0` on every line, so the count is read from the
    last `#N` line instead and divided by the session's own wall time.
    """
    counts = re.findall(r"^#(\d+)", log, re.M)
    return int(counts[-1]) if counts else 0


def triage(binary, crashes, limit=0, jobs=8):
    """`{signature: [crash, ...]}` for *crashes* run through *binary*.

    Each run is a fraction of a second, so they go through `subprocess`
    directly and in parallel rather than through a progress display per input.
    Smallest first, so with a `limit` the reproducers kept are the small ones.
    """
    import subprocess
    from concurrent.futures import ThreadPoolExecutor

    crashes = sorted(crashes, key=lambda p: (p.stat().st_size, p.name))
    if limit:
        crashes = crashes[:limit]

    def one(crash):
        try:
            done = subprocess.run(
                [str(binary), str(crash)],
                capture_output=True,
                text=True,
                errors="replace",
                timeout=60,
                env=Fuzzer.environment(),
            )
            return crash, signature(done.stderr + done.stdout)
        except subprocess.TimeoutExpired:
            return crash, "timeout @ replay"

    buckets = {}
    with ThreadPoolExecutor(jobs) as pool:
        for crash, key in pool.map(one, crashes):
            buckets.setdefault(key, []).append(crash)
    return buckets


