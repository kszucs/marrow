"""Coverage-guided fuzzing with libFuzzer, and the replay of what it found.

A **target** is a file `fuzz/<name>.mojo` defining

    def fuzz_one(data: Span[UInt8, _]) raises

Raising is the correct answer to malformed input; an abort, a signal or a
sanitizer report is a bug.  The harness holds nothing else -- the libFuzzer
entry points and the replay driver are generated here, so the rules every
target must follow live in one place.

Two builds of the same harness:

- **fuzzing** (`Fuzzer`): `mojo build --emit llvm-bitcode`, then clang adds
  SanitizerCoverage and AddressSanitizer and links libFuzzer.  `mojo build` has
  no coverage flag, which is why clang is involved at all.  The bitcode is
  emitted with `--sanitize address` so its functions carry the
  `sanitize_address` attribute -- without it clang's pass instruments nothing
  -- and `LLVMFuzzerInitialize` routes Mojo's heap through libc, the allocator
  AddressSanitizer replaces.  Each half alone reports no heap overflow at all.
- **replay** (`Replay`): one ordinary `mojo build` of every target behind a
  `main()`, run once per committed input in a fresh process.  Needs no clang,
  so it runs wherever the tests do, and it is also what proves every harness
  still compiles.

The committed corpus is `fuzz/corpus/<target>/`, with an `expected.toml` per
target giving each file's verdict: `accept` and `reject` for inputs the reader
must decode or refuse, `crash` for a reproducer of a known, unfixed bug.  A
crash entry that stops crashing fails the replay too -- the bug was fixed, and
the entry's verdict should move with it.
"""

import os
import platform
import re
import shutil
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path

from .mojo import BuildOptions, write_if_changed

#: What a target file has to define.
ENTRY = re.compile(r"^def\s+fuzz_one\s*\(", re.MULTILINE)

#: The verdicts `expected.toml` may give an entry.
VERDICTS = ("accept", "reject", "crash")

#: Every built artifact carries the platform it is for, so a host and a
#: container working in one tree never run each other's binaries.
PLATFORM = f"{sys.platform}-{platform.machine()}"


# ---------------------------------------------------------------------------
# Targets
# ---------------------------------------------------------------------------


class Targets:
    """The harnesses under `fuzz/`, and where each one's working files go."""

    def __init__(self, repo):
        self._repo = repo

    @property
    def directory(self):
        return self._repo.fuzz_dir

    def names(self):
        """Every target, sorted: each `fuzz/*.mojo` that defines `fuzz_one`.

        A shared module under `fuzz/` defines no entry point and so is not a
        target -- which is what lets harnesses import a helper from beside
        them.
        """
        return sorted(
            path.stem
            for path in self.directory.glob("*.mojo")
            if ENTRY.search(path.read_text())
        )

    def resolve(self, name):
        """*name* if it is a target, else a `ValueError` listing the targets."""
        names = self.names()
        if name not in names:
            raise ValueError(
                f"no fuzz target {name!r}; targets are: {', '.join(names)}"
            )
        return name

    def harness(self, name):
        return self.directory / f"{name}.mojo"

    def corpus(self, name):
        """The committed regression corpus."""
        return self.directory / "corpus" / name

    def work(self, name):
        """Untracked: the binary, seeds, the growing corpus and crashes."""
        return self._repo.fuzz_work_dir / name


