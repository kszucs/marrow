ENTRY_TEMPLATE = """\
# Generated by devkit/fuzzing.py -- do not edit.
from std.ffi import external_call

from {module} import fuzz_one


@export
def LLVMFuzzerInitialize(
    argc: Pointer[Int32, MutUntrackedOrigin],
    argv: Pointer[UInt8, MutUntrackedOrigin],
) abi("C") -> Int32:
    # Mojo allocates through its own tcmalloc, whose blocks carry no redzones;
    # libc's allocator is the one AddressSanitizer replaces.
    external_call["KGEN_CompilerRT_SetAsanAllocators", NoneType]()
    return 0


@export
def LLVMFuzzerTestOneInput(
    data: Pointer[UInt8, MutUntrackedOrigin], size: Int
) abi("C") -> Int32:
    try:
        fuzz_one(Span(unsafe_ptr=data, length=size))
    except:
        pass
    return 0
"""

REPLAY_TEMPLATE = """\
# Generated by devkit/fuzzing.py -- do not edit.
from std.sys import argv

{imports}


def main() raises:
    var args = argv()
    if len(args) != 3:
        raise Error("usage: replay TARGET FILE")
    var target = String(args[1])
    var data: List[UInt8]
    with open(String(args[2]), "r") as f:
        data = f.read_bytes()
    try:
{dispatch}
        else:
            raise Error("unknown fuzz target: " + target)
    except e:
        print("reject:", e)
        return
    print("accept")
"""


def entry_source(name):
    """The libFuzzer entry points around target *name*."""
    return ENTRY_TEMPLATE.format(module=name)


def replay_source(names):
    """One `main()` dispatching to every target in *names*."""
    imports = "\n".join(f"from {n} import fuzz_one as {n}" for n in names)
    arms = []
    for i, n in enumerate(names):
        keyword = "if" if i == 0 else "elif"
        arms.append(f'        {keyword} target == "{n}":\n            {n}(Span(data))')
    return REPLAY_TEMPLATE.format(imports=imports, dispatch="\n".join(arms))


